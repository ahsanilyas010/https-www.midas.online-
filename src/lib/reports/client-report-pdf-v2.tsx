import "server-only";
import { Document, Page, Text, View, StyleSheet, renderToBuffer } from "@react-pdf/renderer";
import { BRAND } from "@/lib/brand";
import type { ClientPortalData } from "@/lib/actions/client-portal";

// A real-workspace monthly client report — separate from the legacy
// src/lib/reports/client-report-pdf.tsx (demo-store-backed). Same visual
// language, simpler data shape (this workspace's real
// funnel/outcomes/activity, from the SECURITY DEFINER functions in
// migration 00000000000064).
const BRAND_BLUE = "#4338ca";
const INK = "#16132d";
const MUTED = "#6b7482";
const LINE = "#e2e5ea";

const styles = StyleSheet.create({
  page: { padding: 36, fontSize: 10, color: INK, fontFamily: "Helvetica" },
  title: { fontSize: 16, fontFamily: "Helvetica-Bold" },
  subtitle: { fontSize: 9, color: MUTED, marginTop: 2, marginBottom: 20 },
  sectionTitle: { fontSize: 12, fontFamily: "Helvetica-Bold", marginTop: 16, marginBottom: 8 },
  table: { borderWidth: 1, borderColor: LINE, borderRadius: 4 },
  tableHeaderRow: { flexDirection: "row", backgroundColor: "#f7f8fa", borderBottomWidth: 1, borderBottomColor: LINE },
  tableRow: { flexDirection: "row", borderBottomWidth: 1, borderBottomColor: LINE },
  cellHeader: { flex: 1, fontSize: 8, color: MUTED, padding: 6, textTransform: "uppercase" },
  cell: { flex: 1, fontSize: 9, padding: 6 },
  footer: { position: "absolute", bottom: 24, left: 36, right: 36, fontSize: 8, color: MUTED },
});

interface ReportProps extends ClientPortalData {
  monthLabel: string;
}

function ClientReportDocument({ monthLabel, funnel, outcomes, activity }: ReportProps) {
  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <Text style={styles.title}>{BRAND.productName} — Client report</Text>
        <Text style={styles.subtitle}>{monthLabel}</Text>

        <Text style={styles.sectionTitle}>Campaign funnel</Text>
        <View style={styles.table}>
          <View style={styles.tableHeaderRow}>
            {["Campaign", "Loaded", "Screened", "Dialled", "Connected", "Converted"].map((h) => (
              <Text key={h} style={styles.cellHeader}>
                {h}
              </Text>
            ))}
          </View>
          {funnel.map((f) => (
            <View key={f.campaign_id} style={styles.tableRow}>
              <Text style={styles.cell}>{f.campaign_name}</Text>
              <Text style={styles.cell}>{f.loaded}</Text>
              <Text style={styles.cell}>{f.screened}</Text>
              <Text style={styles.cell}>{f.dialled}</Text>
              <Text style={styles.cell}>{f.connected}</Text>
              <Text style={styles.cell}>{f.converted}</Text>
            </View>
          ))}
        </View>

        <Text style={styles.sectionTitle}>Outcomes</Text>
        <View style={styles.table}>
          <View style={styles.tableHeaderRow}>
            <Text style={styles.cellHeader}>Outcome</Text>
            <Text style={styles.cellHeader}>Group</Text>
            <Text style={styles.cellHeader}>Count</Text>
          </View>
          {outcomes.map((o) => (
            <View key={o.disposition_label} style={styles.tableRow}>
              <Text style={styles.cell}>{o.disposition_label}</Text>
              <Text style={styles.cell}>{o.outcome_group}</Text>
              <Text style={styles.cell}>{o.count}</Text>
            </View>
          ))}
        </View>

        <Text style={styles.sectionTitle}>Agent activity</Text>
        <View style={styles.table}>
          <View style={styles.tableHeaderRow}>
            <Text style={styles.cellHeader}>Agent</Text>
            <Text style={styles.cellHeader}>Calls</Text>
            <Text style={styles.cellHeader}>Connects</Text>
            <Text style={styles.cellHeader}>Conversions</Text>
          </View>
          {activity.map((a) => (
            <View key={a.agent_label} style={styles.tableRow}>
              <Text style={styles.cell}>{a.agent_label}</Text>
              <Text style={[styles.cell, { color: BRAND_BLUE }]}>{a.calls}</Text>
              <Text style={styles.cell}>{a.connects}</Text>
              <Text style={styles.cell}>{a.conversions}</Text>
            </View>
          ))}
        </View>

        <Text style={styles.footer}>Generated by {BRAND.productName}. Never includes lead phone numbers or recordings.</Text>
      </Page>
    </Document>
  );
}

export async function renderClientReportPdf(props: ReportProps): Promise<Buffer> {
  return renderToBuffer(<ClientReportDocument {...props} />);
}
